function metrics = positiveStepMetrics(t,response,command)
i10 = find(response >= 0.10*command,1,'first');
i90 = find(response >= 0.90*command,1,'first');
if isempty(i10) || isempty(i90)
    metrics.riseTime_s = inf;
else
    metrics.riseTime_s = t(i90)-t(i10);
end
metrics.overshoot_pct = max(0,100*(max(response)-command)/command);
outside = find(abs(response-command) > 0.02*abs(command));
if isempty(outside)
    metrics.settlingTime_s = 0;
elseif outside(end) == numel(t)
    metrics.settlingTime_s = inf;
else
    metrics.settlingTime_s = t(outside(end)+1);
end
end

function settlingTime_s = wrappedSettlingTime(t,response,command, ...
    toleranceFraction)
errorMagnitude = abs(wrapAngle(command-response));
outside = find(errorMagnitude > toleranceFraction*abs(command));
if isempty(outside)
    settlingTime_s = 0.0;
elseif outside(end) == numel(t)
    settlingTime_s = inf;
else
    settlingTime_s = t(outside(end)+1);
end
end

function value = wrapAngle(value)
value = atan2(sin(value),cos(value));
end

function value = clip(value,lowerLimit,upperLimit)
value = min(max(value,lowerLimit),upperLimit);
end

function assertDependencies(data,yawController,rudder,rollController, ...
    aileron,headingSensor,headingController)
assert(strcmp(data.model.version,headingController.requiredPlantVersion), ...
    'Heading Hold V1 plant dependency mismatch.');
assert(strcmp(yawController.artifactRevision, ...
    headingController.requiredYawDamperRevision), ...
    'Heading Hold V1 yaw-controller dependency mismatch.');
assert(strcmp(rudder.artifactRevision, ...
    headingController.requiredRudderAuditRevision), ...
    'Heading Hold V1 rudder-audit dependency mismatch.');
assert(strcmp(aileron.artifactRevision, ...
    headingController.requiredAileronAuditRevision), ...
    'Heading Hold V1 aileron-audit dependency mismatch.');
assert(strcmp(rollController.artifactRevision, ...
    headingController.requiredRollControllerRevision), ...
    'Heading Hold V1 roll-controller dependency mismatch.');
assert(strcmp(headingSensor.artifactRevision, ...
    headingController.requiredHeadingSensorRevision), ...
    'Heading Hold V1 heading-sensor dependency mismatch.');
assert(abs(aileron.sensor.nominalDelay_s-0.010) < 1.0e-12, ...
    'The executable baseline requires the audited 10-ms roll delay.');
assert(abs(rudder.sensor.nominalDelay_s-0.010) < 1.0e-12, ...
    'The executable baseline requires the audited 10-ms yaw delay.');
assert(abs(headingSensor.nominalDelay_s-0.050) < 1.0e-12, ...
    'The executable baseline requires the audited 50-ms heading delay.');
assert(abs(headingController.bankCommandAuthority_deg- ...
    rollController.commandAuthority.rightWingDown_deg) < 1.0e-12, ...
    'Heading Hold V1 must reuse the frozen RAH bank authority.');
end

function [t,y] = extractArrayOutput(simOut,nSignal)
t = simOut.tout;
y = simOut.yout;
if isa(y,'timeseries')
    y = y.Data;
elseif isa(y,'Simulink.SimulationData.Dataset')
    y = y.getElement(1).Values.Data;
end
y = squeeze(y);
if size(y,1) ~= numel(t) && size(y,2) == numel(t)
    y = y.';
end
assert(size(y,2) == nSignal, ...
    'Expected %d logged signals but received %d.',nSignal,size(y,2));
end

