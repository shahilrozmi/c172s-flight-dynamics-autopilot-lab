    I.(names{k}) = k;
end
end

function metrics = protectedStressMetrics(capture,I,aileron)
y = capture.ySim;
metrics.positionLimitActive = aileronPositionLimitActive(y,I);
metrics.rateLimitActive = aileronRateLimitActive(y,I);
metrics.physicalLimitActive = aileronPhysicalLimitActive(y,I);
metrics.peakAutomaticAileron_deg = max(abs(rad2deg(y(:,I.aileronActual))));
metrics.peakAileronRate_degps = max(abs(rad2deg(y(:,I.aileronRate))));
metrics.peakIntegratorMagnitude = max(abs(y(:,I.xi)));
metrics.finalBank_deg = rad2deg(y(end,I.phi));
metrics.finalAutomaticAileron_deg = rad2deg(y(end,I.aileronActual));
inside = abs(rad2deg(y(:,I.phi))) <= aileron.stress.recoveryThreshold_deg;
lastOutside = find(~inside,1,'last');
if isempty(lastOutside)
    metrics.recoveryTime_s = capture.t(1);
elseif lastOutside < numel(capture.t)
    metrics.recoveryTime_s = capture.t(lastOutside+1);
else
    metrics.recoveryTime_s = inf;
end
end

