function cfg = captureConfiguration(caseName,~,aileron, ...
    headingSensor,headingController)
cfg.name = caseName;
cfg.headingCommand_rad = 0.0;
cfg.headingBias_rad = 0.0;
cfg.headingNoiseAmplitude_rad = 0.0;
cfg.headingNoiseFrequency_radps = headingSensor.noiseFrequency_radps;
cfg.aileronBias_rad = 0.0;
cfg.aileronPulse_rad = 0.0;
cfg.rudderBias_rad = 0.0;
cfg.rudderPulse_rad = 0.0;
cfg.aileronPulseStart_s = 5.0;
cfg.aileronPulseEnd_s = 6.0;
cfg.rudderPulseStart_s = 5.0;
cfg.rudderPulseEnd_s = 6.0;
cfg.pNoiseAmplitude_radps = 0.0;
cfg.pNoiseFrequency_radps = aileron.noise.rollRateFrequency_radps;
cfg.phiNoiseAmplitude_rad = 0.0;
cfg.phiNoiseFrequency_radps = aileron.noise.bankAngleFrequency_radps;
cfg.antiWindupEnable = 1.0;
cfg.x0 = zeros(5,1);
cfg.stopTime_s = headingController.validation.stopTime_s;

switch caseName
    case 'command'
        cfg.headingCommand_rad = deg2rad( ...
            headingController.validation.commandStep_deg);
    case 'largeTurn'
        cfg.headingCommand_rad = deg2rad( ...
            headingController.validation.largeCommandStep_deg);
        cfg.stopTime_s = headingController.validation.nonlinearStopTime_s;
    case 'wrapRight'
        cfg.x0(5) = deg2rad( ...
            headingController.validation.wrapRightInitial_deg);
        cfg.headingCommand_rad = deg2rad( ...
            headingController.validation.wrapRightCommand_deg);
    case 'wrapLeft'
        cfg.x0(5) = deg2rad( ...
            headingController.validation.wrapLeftInitial_deg);
        cfg.headingCommand_rad = deg2rad( ...
            headingController.validation.wrapLeftCommand_deg);
    case 'bias'
        cfg.headingBias_rad = deg2rad(headingSensor.biasStress_deg);
    case 'aileronPulse'
        cfg.aileronPulse_rad = deg2rad(1.0);
    case 'rudderPulse'
        cfg.rudderPulse_rad = deg2rad(1.0);
    case 'stressAw'
        cfg.x0(4) = deg2rad(aileron.stress.initialBank_deg);
        cfg.antiWindupEnable = 1.0;
    case 'stressNoAw'
        cfg.x0(4) = deg2rad(aileron.stress.initialBank_deg);
        cfg.antiWindupEnable = 0.0;
    case 'noise'
        cfg.headingNoiseAmplitude_rad = deg2rad( ...
            sqrt(2)*headingSensor.noiseStressRms_deg);
        cfg.stopTime_s = headingSensor.noiseStopTime_s;
    otherwise
        error('Unknown capture name: %s',caseName);
end
end

function y = independentReference(t,cfg,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController)
% Continuous z = [beta p r phi psi rSensor xw deltaR pSensor phiSensor
%                 xi deltaA filteredCommand headingSensor].
z = [cfg.x0;zeros(8,1);cfg.x0(5)+cfg.headingBias_rad];
delay.r = cfg.x0(3);
delay.p = cfg.x0(2);
delay.phi = cfg.x0(4);
delay.psi = repmat(cfg.x0(5),5,1);
y = zeros(numel(t),52);
for k = 1:numel(t)
    d = protectedSignals(t(k),z,delay,cfg,yawController,rudder, ...
        rollController,aileron,headingController);
    y(k,:) = outputVector(z,d).';
    if k < numel(t)
        h = t(k+1)-t(k);
        sampled.r = z(3);
        sampled.p = z(2);
        sampled.phi = z(4);
        sampled.psi = z(5);
        k1 = protectedDerivative(t(k),z,delay,cfg,plant, ...
            yawController,rudder,rollController,aileron,headingSensor, ...
            headingController);
        k2 = protectedDerivative(t(k)+0.5*h,z+0.5*h*k1,delay,cfg, ...
            plant,yawController,rudder,rollController,aileron, ...
            headingSensor,headingController);
        k3 = protectedDerivative(t(k)+0.5*h,z+0.5*h*k2,delay,cfg, ...
            plant,yawController,rudder,rollController,aileron, ...
            headingSensor,headingController);
        k4 = protectedDerivative(t(k)+h,z+h*k3,delay,cfg,plant, ...
            yawController,rudder,rollController,aileron,headingSensor, ...
            headingController);
        z = z+(h/6)*(k1+2*k2+2*k3+k4);
        delay.r = sampled.r;
        delay.p = sampled.p;
        delay.phi = sampled.phi;
        delay.psi = [delay.psi(2:end);sampled.psi];
    end
end
end

function zDot = protectedDerivative(t,z,delay,cfg,plant, ...
    yawController,rudder,rollController,aileron,headingSensor, ...
    headingController)
d = protectedSignals(t,z,delay,cfg,yawController,rudder, ...
    rollController,aileron,headingController);
zDot = zeros(14,1);
zDot(1:5) = plant.A*z(1:5)+plant.B*[d.totalAileron;d.totalRudder];
zDot(6) = (d.rInput-z(6))/rudder.sensor.filterTimeConstant_s;
zDot(7) = (z(6)-z(7))/yawController.washoutTimeConstant_s;
zDot(8) = d.rudderRate;
zDot(9) = (d.pInput-z(9))/aileron.sensor.filterTimeConstant_s;
zDot(10) = (d.phiInput-z(10))/aileron.sensor.filterTimeConstant_s;
zDot(11) = d.bankError+d.antiWindup;
zDot(12) = d.aileronRate;
zDot(13) = (d.bankCommandLimited-z(13))/ ...
    rollController.commandFilterTimeConstant_s;
zDot(14) = (d.headingInput-z(14))/ ...
    headingSensor.filterTimeConstant_s;
end

function d = protectedSignals(t,z,delay,cfg,yawController,rudder, ...
    rollController,aileron,headingController)
d.headingCommand = cfg.headingCommand_rad;
d.psiDelayed = delay.psi(1);
d.headingBias = cfg.headingBias_rad;
d.headingNoise = cfg.headingNoiseAmplitude_rad* ...
    sin(cfg.headingNoiseFrequency_radps*t);
d.headingInput = d.psiDelayed+d.headingBias+d.headingNoise;
d.headingDifference = d.headingCommand-z(14);
d.headingError = wrapAngle(d.headingDifference);
d.bankCommandRaw = headingController.headingErrorGain*d.headingError;
bankLimit = deg2rad(headingController.bankCommandAuthority_deg);
d.bankCommandLimited = clip(d.bankCommandRaw,-bankLimit,bankLimit);
[d.aileronPilot,d.rudderPilot] = pilotInputs(t,cfg);
d.rNoise = 0.0;
d.pNoise = cfg.pNoiseAmplitude_radps*sin(cfg.pNoiseFrequency_radps*t);
d.phiNoise = cfg.phiNoiseAmplitude_rad*sin(cfg.phiNoiseFrequency_radps*t);
d.rDelayed = delay.r;
d.pDelayed = delay.p;
d.phiDelayed = delay.phi;
d.rInput = d.rDelayed+d.rNoise;
d.pInput = d.pDelayed+d.pNoise;
d.phiInput = d.phiDelayed+d.phiNoise;

d.rWashout = z(6)-z(7);
d.rudderRaw = -yawController.rudderGain_s*d.rWashout;
d.rudderPosition = clip(d.rudderRaw,rudder.authority.lowerLimit_rad, ...
    rudder.authority.upperLimit_rad);
d.rudderRateRaw = (d.rudderPosition-z(8))/ ...
    rudder.dynamics.timeConstant_s;
d.rudderRate = clip(d.rudderRateRaw, ...
    -deg2rad(rudder.dynamics.rateLimit_degps), ...
    deg2rad(rudder.dynamics.rateLimit_degps));
d.rudderTotalRaw = d.rudderPilot+z(8);
d.totalRudder = clip(d.rudderTotalRaw, ...
    rudder.physicalTravel.lowerLimit_rad, ...
    rudder.physicalTravel.upperLimit_rad);

d.bankError = z(13)-z(10);
d.proportional = rollController.bankProportionalGain*d.bankError;
d.integral = rollController.bankIntegralGain_per_s*z(11);
d.rollRateContribution = -rollController.rollRateGain_s*z(9);
d.aileronUnsat = d.proportional+d.integral+d.rollRateContribution;
d.aileronPosition = clip(d.aileronUnsat, ...
    aileron.authority.lowerLimit_rad,aileron.authority.upperLimit_rad);
d.aileronRateRaw = (d.aileronPosition-z(12))/ ...
    aileron.dynamics.timeConstant_s;
d.aileronRate = clip(d.aileronRateRaw, ...
    -deg2rad(aileron.dynamics.rateLimit_degps), ...
    deg2rad(aileron.dynamics.rateLimit_degps));
d.aileronTrack = z(12)+ ...
    aileron.dynamics.timeConstant_s*d.aileronRate;
d.antiWindup = cfg.antiWindupEnable*(d.aileronTrack-d.aileronUnsat)/( ...
    rollController.bankIntegralGain_per_s* ...
    aileron.antiWindup.trackingTimeConstant_s);
d.aileronTotalRaw = d.aileronPilot+z(12);
d.totalAileron = clip(d.aileronTotalRaw, ...
    aileron.physicalTravel.lowerLimit_rad, ...
    aileron.physicalTravel.upperLimit_rad);
end

function y = outputVector(z,d)
y = [z(1:5);d.headingCommand;d.psiDelayed;d.headingBias; ...
    d.headingNoise;d.headingInput;z(14);d.headingDifference; ...
    d.headingError;d.bankCommandRaw;d.bankCommandLimited;z(13); ...
    d.aileronPilot;d.rudderPilot;d.rDelayed;d.rNoise;d.rInput;z(6); ...
    d.rWashout;d.rudderRaw;d.rudderPosition;z(8);d.rudderRateRaw; ...
    d.rudderRate;d.rudderTotalRaw;d.totalRudder;d.pDelayed;d.pNoise; ...
    d.pInput;z(9);d.phiDelayed;d.phiNoise;d.phiInput;z(10); ...
    d.bankError;d.proportional;z(11);d.integral; ...
    d.rollRateContribution;d.aileronUnsat;d.aileronPosition;z(12); ...
    d.aileronRateRaw;d.aileronRate;d.aileronTrack;d.antiWindup; ...
    d.aileronTotalRaw;d.totalAileron];
end

function [aileronInput,rudderInput] = pilotInputs(t,cfg)
t = snapToEdges(t,[cfg.aileronPulseStart_s,cfg.aileronPulseEnd_s, ...
    cfg.rudderPulseStart_s,cfg.rudderPulseEnd_s]);
aileronInput = cfg.aileronBias_rad;
rudderInput = cfg.rudderBias_rad;
if t >= cfg.aileronPulseStart_s && t < cfg.aileronPulseEnd_s
    aileronInput = aileronInput+cfg.aileronPulse_rad;
end
if t >= cfg.rudderPulseStart_s && t < cfg.rudderPulseEnd_s
    rudderInput = rudderInput+cfg.rudderPulse_rad;
end
end

function t = snapToEdges(t,edges)
for k = 1:numel(edges)
    if abs(t-edges(k)) <= 1.0e-12
        t = edges(k);
        return;
    end
end
end

