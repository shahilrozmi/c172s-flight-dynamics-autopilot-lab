    headingSensor.requirements.maximumBiasResidualMismatch_deg, ...
    'The heading-bias case did not expose the true-heading residual.');

aileronPulsePeakHeading_deg = max(abs(rad2deg( ...
    aileronPulseCapture.ySim(:,I.psi))));
