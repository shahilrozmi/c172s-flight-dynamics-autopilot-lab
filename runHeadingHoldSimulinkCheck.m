headingSensor = c172sHeadingSensorData();
headingController = c172sHeadingHoldControllerData();
assertDependencies(data,yawController,rudder,rollController,aileron, ...
    headingSensor,headingController);

% Rebuild the generated diagram so a stale or hand-edited SLX cannot
% influence the implementation-equivalence result.
modelName = buildC172sHeadingHoldSimulink(true);

%% Ten independent executable captures

commandCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'command');
largeTurnCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'largeTurn');
wrapRightCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'wrapRight');
wrapLeftCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'wrapLeft');
biasCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'bias');
aileronPulseCapture = runCapture(modelName,plant,yawController,rudder, ...
    rollController,aileron,headingSensor,headingController,'aileronPulse');
