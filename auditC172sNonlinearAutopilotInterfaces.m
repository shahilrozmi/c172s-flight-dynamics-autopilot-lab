elevatorControl = mapControls([small;0;0],interface);
aileronControl = mapControls([0;small;0],interface);
rudderControl = mapControls([0;0;small],interface);
record('Elevator sign maps without inversion', ...
    elevatorControl(1) > trim.controls(1), ...
    'positive controller elevator remains trailing-edge down');
record('Aileron sign maps without inversion', ...
    aileronControl(2) > trim.controls(2), ...
    'positive controller aileron remains right-wing-down');
record('Rudder sign maps without inversion', ...
    rudderControl(3) > trim.controls(3), ...
    'positive controller rudder remains nose-right');
record('Throttle ownership remains explicit', ...
    ~interface.controls.autothrottleImplemented && ...
    abs(interface.controls.fixedThrottle-trim.controls(4)) <= ...
    interface.validation.maximumTrimMappingError && ...
    abs(elevatorControl(4)-trim.controls(4)) <= ...
    interface.validation.maximumTrimMappingError, ...
    'fixed one-point throttle 0.65; no autothrottle claim');

authorityMatch = abs(interface.plant.controlLower(1)- ...
    elevator.authority.lowerLimit_rad) < eps && ...
    abs(interface.plant.controlUpper(1)- ...
    elevator.authority.upperLimit_rad) < eps && ...
    abs(interface.plant.controlLower(2)- ...
    aileron.authority.lowerLimit_rad) < eps && ...
    abs(interface.plant.controlUpper(2)- ...
    aileron.authority.upperLimit_rad) < eps && ...
    abs(interface.plant.controlLower(3)- ...
    rudder.authority.lowerLimit_rad) < eps && ...
    abs(interface.plant.controlUpper(3)- ...
    rudder.authority.upperLimit_rad) < eps && ...
    norm(interface.plant.controlLower-trimData.controls.lower,inf) < eps && ...
    norm(interface.plant.controlUpper-trimData.controls.upper,inf) < eps;
record('Automatic surface authorities are compatible',authorityMatch, ...
    'plant and released actuator paths share +/-5-deg bounds');
record('Out-of-bounds surfaces are rejected',throws(@() ...
    mapControls([deg2rad(5.01);0;0],interface), ...
    'auditC172sNonlinearAutopilotInterfaces:SurfaceOutsideBounds'), ...
    'adapter does not silently clip or enlarge actuator authority');

