    strcmp(interface.required.elevatorLoop,elevator.integratedLoopVersion) && ...
    strcmp(interface.required.aileronAudit,aileron.artifactRevision) && ...
    strcmp(interface.required.rudderAudit,rudder.artifactRevision), ...
    'elevator, aileron and rudder dependency identifiers match');
