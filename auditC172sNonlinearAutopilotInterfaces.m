    interface.trim.weight_lb == 2550 && ...
    abs(interface.trim.altitude_m-trimData.trim.altitude_m) < 1e-12 && ...
    abs(interface.trim.TAS_mps-trimData.trim.TAS_mps) < 1e-12, ...
    '4000 ft ISA / 110 KTAS / 2550 lb');
record('Common deterministic execution rate', ...
    strcmp(interface.execution.solver,integration.execution.solver) && ...
    interface.execution.fixedStep_s == integration.execution.fixedStep_s && ...
    interface.execution.supervisorSampleTime_s == ...
    manager.validation.sampleTime_s && ...
    interface.execution.controllerSampleTime_s == ...
    manager.validation.sampleTime_s && ...
    interface.execution.fixedStep_s == plant.integration.fixedStep_s, ...
    'ode4 / 0.010 s for plant, controllers and supervisor');

record('Actuator dynamics have one owner', ...
    interface.controls.inputRepresentsActualSurfacePosition && ...
    ~interface.controls.adapterAddsActuatorDynamics && ...
    ~interface.controls.adapterAddsRateLimiting && ...
    ~interface.controls.adapterAddsSaturation, ...
    'released controller stacks own dynamics, rates and limits');
record('Control adapter is identity plus trim', ...
    isequal(interface.controls.surfaceMappingMatrix,eye(3)) && ...
    norm(interface.controls.surfaceTrimOffset_rad,inf) == 0, ...
    'actual controller surfaces map one-to-one at the zero-surface trim');
record('Nonlinear trim control vector recovered', ...
    norm(interface.trim.controlVector-trim.controls,inf) <= ...
    interface.validation.maximumTrimMappingError, ...
    sprintf('[deltaE deltaA deltaR throttle] = [0 0 0 %.2f]', ...
    interface.trim.throttle));

