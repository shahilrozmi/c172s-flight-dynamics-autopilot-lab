function controls = mapControls(actualSurface_rad,interface)
if ~(isnumeric(actualSurface_rad) && isreal(actualSurface_rad) && ...
        isequal(size(actualSurface_rad),[3,1]) && ...
        all(isfinite(actualSurface_rad)))
    error('auditC172sNonlinearAutopilotInterfaces:InvalidSurfaceInput', ...
        'Actual surface input must be a finite real 3x1 column.');
end
surface = interface.controls.surfaceTrimOffset_rad+ ...
    interface.controls.surfaceMappingMatrix*actualSurface_rad;
if any(surface < interface.plant.controlLower(1:3)-1e-14) || ...
        any(surface > interface.plant.controlUpper(1:3)+1e-14)
    error('auditC172sNonlinearAutopilotInterfaces:SurfaceOutsideBounds', ...
        'An actual surface position exceeds the frozen plant authority.');
end
controls = [surface;interface.controls.fixedThrottle];
end

function commands = mapCommands(managerCommands,interface)
if ~(isnumeric(managerCommands) && isreal(managerCommands) && ...
        isequal(size(managerCommands),[4,1]) && ...
        all(isfinite(managerCommands)))
    error('auditC172sNonlinearAutopilotInterfaces:InvalidCommandInput', ...
        'Manager command input must be a finite real 4x1 column.');
end
commands.bankCommand_rad = ...
    managerCommands(1)*interface.conversions.degToRad;
commands.pitchCommand_rad = ...
    managerCommands(2)*interface.conversions.degToRad;
commands.headingCommand_rad = mod( ...
    managerCommands(3)*interface.conversions.degToRad,2*pi);
commands.altitudeCommandPerturbation_m = ...
    (managerCommands(4)-interface.trim.altitude_ft)* ...
    interface.conversions.ftToM;
end

function feedback = mapFeedback(state,stateDerivative,steadyWind,gust, ...
    interface,plant)
if ~(isnumeric(state) && isreal(state) && isequal(size(state),[13,1]) && ...
        all(isfinite(state))) || ...
   ~(isnumeric(stateDerivative) && isreal(stateDerivative) && ...
        isequal(size(stateDerivative),[13,1]) && ...
        all(isfinite(stateDerivative)))
    error('auditC172sNonlinearAutopilotInterfaces:InvalidState', ...
        'State and state derivative must be finite real 13x1 columns.');
end
if ~(isnumeric(steadyWind) && isequal(size(steadyWind),[3,1]) && ...
        all(isfinite(steadyWind))) || ...
   ~(isnumeric(gust) && isequal(size(gust),[3,1]) && all(isfinite(gust)))
    error('auditC172sNonlinearAutopilotInterfaces:InvalidWind', ...
        'Steady wind and gust must be finite 3x1 NED columns.');
end

q = state(10:13);
qNorm = norm(q);
if qNorm <= eps || ...
        abs(qNorm-1) > interface.validity.maximumQuaternionNormError
    error('auditC172sNonlinearAutopilotInterfaces:InvalidQuaternion', ...
        'Quaternion norm is outside the frozen interface tolerance.');
end
q = q/qNorm;
[phi,theta,psiRaw] = quaternionToEuler(q);
psi = mod(psiRaw,2*pi);
altitude_m = -state(9);
verticalSpeed_mps = -stateDerivative(9);
air = c172sAtmosphereAirData(state,steadyWind,gust, ...
    plant.trimModel.aerodynamics.airDataModel);

feedback.controller.q_radps = state(5);
feedback.controller.theta_rad = theta;
feedback.controller.altitudePerturbation_m = ...
    altitude_m-interface.trim.altitude_m;
feedback.controller.verticalSpeed_mps = verticalSpeed_mps;
feedback.controller.p_radps = state(4);
feedback.controller.r_radps = state(6);
feedback.controller.phi_rad = phi;
feedback.controller.psi_rad = psi;

feedback.supervisor.bank_deg = rad2deg(phi);
feedback.supervisor.pitch_deg = rad2deg(theta);
feedback.supervisor.heading_deg = mod(rad2deg(psi),360);
feedback.supervisor.altitude_ft = ...
    altitude_m*interface.conversions.mToFt;

feedback.monitor.TAS_mps = air.TAS_mps;
feedback.monitor.alpha_rad = air.alpha_rad;
feedback.monitor.beta_rad = air.beta_rad;
feedback.monitor.quaternionNorm = qNorm;
feedback.monitor.withinV01Envelope = air.valid && ...
    air.TAS_mps >= interface.envelope.V_KTAS(1)*0.514444444444444 && ...
    air.TAS_mps <= interface.envelope.V_KTAS(2)*0.514444444444444 && ...
    air.alpha_rad >= deg2rad(interface.envelope.alpha_deg(1)) && ...
    air.alpha_rad <= deg2rad(interface.envelope.alpha_deg(2)) && ...
    air.beta_rad >= deg2rad(interface.envelope.beta_deg(1)) && ...
    air.beta_rad <= deg2rad(interface.envelope.beta_deg(2)) && ...
    phi >= deg2rad(interface.envelope.bank_deg(1)) && ...
    phi <= deg2rad(interface.envelope.bank_deg(2)) && ...
    theta >= deg2rad(interface.envelope.pitch_deg(1)) && ...
    theta <= deg2rad(interface.envelope.pitch_deg(2));

feedback.validity.coreSensorsValid = all(isfinite(state(4:6))) && ...
    abs(qNorm-1) <= interface.validity.maximumQuaternionNormError;
feedback.validity.headingValid = feedback.validity.coreSensorsValid && ...
    isfinite(psi);
feedback.validity.altitudeValid = isfinite(altitude_m);
feedback.validity.airDataValid = air.valid;
end

function supervisor = makeAngleFeedback(phi_deg,theta_deg,psi_deg,trim, ...
    stateDerivative,interface,plant)
state = trim.state;
state(10:13) = eulerToQuaternion( ...
    deg2rad(phi_deg),deg2rad(theta_deg),deg2rad(psi_deg));
feedback = mapFeedback(state,stateDerivative,zeros(3,1),zeros(3,1), ...
    interface,plant);
supervisor = feedback.supervisor;
end

function q = eulerToQuaternion(phi,theta,psi)
cr = cos(phi/2); sr = sin(phi/2);
cp = cos(theta/2); sp = sin(theta/2);
cy = cos(psi/2); sy = sin(psi/2);
q = [ ...
    cr*cp*cy+sr*sp*sy; ...
    sr*cp*cy-cr*sp*sy; ...
    cr*sp*cy+sr*cp*sy; ...
    cr*cp*sy-sr*sp*cy];
q = q/norm(q);
end

function [phi,theta,psi] = quaternionToEuler(q)
q0 = q(1); q1 = q(2); q2 = q(3); q3 = q(4);
phi = atan2(2*(q0*q1+q2*q3),1-2*(q1^2+q2^2));
argument = 2*(q0*q2-q3*q1);
argument = min(max(argument,-1),1);
theta = asin(argument);
psi = atan2(2*(q0*q3+q1*q2),1-2*(q2^2+q3^2));
end

function yes = throws(action,identifier)
yes = false;
try
    action();
catch exception
    yes = strcmp(exception.identifier,identifier);
end
end
