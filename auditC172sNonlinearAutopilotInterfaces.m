    trim.state,trim.controls,zeroWind,zeroWind,plant);
trimFeedback = mapFeedback(trim.state,trimDerivative,zeroWind,zeroWind, ...
    interface,plant);

record('Scalar-first body-to-NED quaternion preserved', ...
    strcmp(interface.plant.quaternionOrder,source.state.quaternionOrder) && ...
    abs(trim.state(10)-1) <= ...
    interface.validation.maximumAngleConversionError && ...
    norm(trim.state(11:13),inf) <= ...
    interface.validation.maximumAngleConversionError, ...
    'trim quaternion [1 0 0 0]');
record('Identity quaternion maps to level attitude', ...
    max(abs([trimFeedback.controller.phi_rad, ...
    trimFeedback.controller.theta_rad, ...
    trimFeedback.controller.psi_rad])) <= ...
    interface.validation.maximumAngleConversionError, ...
    'phi/theta/psi are zero at trim');

testEuler = deg2rad([12;-7;31]);
testState = trim.state;
testState(10:13) = eulerToQuaternion( ...
    testEuler(1),testEuler(2),testEuler(3));
testFeedback = mapFeedback(testState,trimDerivative,zeroWind,zeroWind, ...
    interface,plant);
eulerError = max(abs([testFeedback.controller.phi_rad; ...
    testFeedback.controller.theta_rad; ...
    testFeedback.controller.psi_rad]-testEuler));
record('Quaternion-to-Euler sequence is correct', ...
    eulerError <= interface.validation.maximumAngleConversionError, ...
    sprintf('3-2-1 round-trip error %.3g rad',eulerError));
record('Positive bank sign is preserved', ...
    testFeedback.supervisor.bank_deg > 0, ...
    'positive phi reports right-wing-down bank');
positivePitch = makeAngleFeedback(0,5,0,trim,trimDerivative, ...
    interface,plant);
record('Positive pitch sign is preserved', ...
    positivePitch.pitch_deg > 0, ...
    'positive theta reports nose-up pitch');
positiveHeading = makeAngleFeedback(0,0,5,trim,trimDerivative, ...
    interface,plant);
record('Positive heading sign is preserved', ...
    positiveHeading.heading_deg > 0, ...
    'positive psi reports clockwise/nose-right heading');

negativeHeading = makeAngleFeedback(0,0,-10,trim,trimDerivative, ...
    interface,plant);
largeHeading = makeAngleFeedback(0,0,370,trim,trimDerivative, ...
    interface,plant);
record('Heading normalization is circular', ...
    abs(negativeHeading.heading_deg-350) < ...
    interface.validation.maximumAngleConversionError && ...
    abs(largeHeading.heading_deg-10) < ...
    interface.validation.maximumAngleConversionError, ...
    '-10 deg -> 350 deg and 370 deg -> 10 deg');

record('NED-down altitude sign is preserved', ...
    abs(trimFeedback.supervisor.altitude_ft-4000) <= ...
    interface.validation.maximumUnitConversionError, ...
    'positionDown = -1219.2 m maps to +4000 ft');
climbDerivative = trimDerivative;
climbDerivative(9) = -2.0;
climbFeedback = mapFeedback(trim.state,climbDerivative,zeroWind,zeroWind, ...
    interface,plant);
record('Vertical-speed sign is climb-positive', ...
    climbFeedback.controller.verticalSpeed_mps == 2.0, ...
    'positionDownDot -2 m/s maps to climb +2 m/s');
record('Trim altitude perturbation is zero', ...
    abs(trimFeedback.controller.altitudePerturbation_m) <= ...
    interface.validation.maximumTrimMappingError, ...
    'absolute 4000 ft becomes zero outer-loop perturbation');
record('Trim controller feedback is zero', ...
    max(abs([trimFeedback.controller.q_radps, ...
    trimFeedback.controller.theta_rad, ...
    trimFeedback.controller.verticalSpeed_mps, ...
    trimFeedback.controller.p_radps, ...
    trimFeedback.controller.r_radps, ...
    trimFeedback.controller.phi_rad, ...
    trimFeedback.controller.psi_rad])) <= ...
    interface.validation.maximumTrimMappingError, ...
    'rates, attitudes and vertical speed close at trim');

record('Controller feedback units are frozen', ...
    interface.feedback.controllerCount == 8 && ...
    isequal(interface.feedback.controllerUnits(:), ...
    {'rad/s';'rad';'m';'m/s';'rad/s';'rad/s';'rad';'rad'}), ...
    'inner/outer loops retain rad, rad/s, m and m/s');
