    isequal(interface.plant.stateNames(:),plant.state.names(:)), ...
    'u v w p q r, NED position and scalar-first quaternion');
record('Four-control plant contract preserved', ...
    interface.plant.controlCount == 4 && plant.control.count == 4 && ...
    isequal(interface.plant.controlNames(:),plant.control.names(:)), ...
    'elevator, aileron, rudder and throttle ordering matches');
record('Common frozen trim point preserved', ...
    interface.trim.altitude_ft == 4000 && ...
