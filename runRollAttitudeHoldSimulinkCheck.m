function result = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,caseName)
cfg = captureConfiguration(caseName,controller,aileron);

simInput = Simulink.SimulationInput(modelName);
simInput = simInput.setVariable('bankCommand_rah1_rad',cfg.bankCommand_rad);
simInput = simInput.setVariable('pilotAileronBias_rah1_rad', ...
    cfg.aileronBias_rad);
simInput = simInput.setVariable('pilotAileronPulse_rah1_rad', ...
    cfg.aileronPulse_rad);
simInput = simInput.setVariable('pilotRudderBias_rah1_rad', ...
    cfg.rudderBias_rad);
simInput = simInput.setVariable('pilotRudderPulse_rah1_rad', ...
    cfg.rudderPulse_rad);
simInput = simInput.setVariable('aileronPulseStart_rah1_s', ...
    cfg.aileronPulseStart_s);
simInput = simInput.setVariable('aileronPulseEnd_rah1_s', ...
    cfg.aileronPulseEnd_s);
simInput = simInput.setVariable('rudderPulseStart_rah1_s', ...
    cfg.rudderPulseStart_s);
simInput = simInput.setVariable('rudderPulseEnd_rah1_s', ...
    cfg.rudderPulseEnd_s);
simInput = simInput.setVariable('pNoiseAmplitude_rah1_radps', ...
    cfg.pNoiseAmplitude_radps);
simInput = simInput.setVariable('pNoiseFrequency_rah1_radps', ...
    cfg.pNoiseFrequency_radps);
simInput = simInput.setVariable('phiNoiseAmplitude_rah1_rad', ...
    cfg.phiNoiseAmplitude_rad);
simInput = simInput.setVariable('phiNoiseFrequency_rah1_radps', ...
    cfg.phiNoiseFrequency_radps);
simInput = simInput.setVariable('yawNoiseAmplitude_rah1_radps',0.0);
simInput = simInput.setVariable('yawNoiseFrequency_rah1_radps',50.0);
simInput = simInput.setVariable('antiWindupEnable_rah1', ...
    cfg.antiWindupEnable);
simInput = simInput.setVariable('x0_rah1',cfg.x0);
simInput = simInput.setVariable('rDelay0_rah1_radps',cfg.x0(3));
simInput = simInput.setVariable('pDelay0_rah1_radps',cfg.x0(2));
simInput = simInput.setVariable('phiDelay0_rah1_rad',cfg.x0(4));
simInput = simInput.setVariable('rSensor0_rah1_radps',0.0);
simInput = simInput.setVariable('xw0_rah1_radps',0.0);
simInput = simInput.setVariable('deltaRAuto0_rah1_rad',0.0);
simInput = simInput.setVariable('pSensor0_rah1_radps',0.0);
simInput = simInput.setVariable('phiSensor0_rah1_rad',0.0);
simInput = simInput.setVariable('xi0_rah1_rad_s',0.0);
simInput = simInput.setVariable('deltaAAuto0_rah1_rad',0.0);
simInput = simInput.setVariable('filteredCommand0_rah1_rad',0.0);
simInput = simInput.setModelParameter('StopTime',num2str(cfg.stopTime_s));

simOut = sim(simInput);
[tSim,ySim] = extractArrayOutput(simOut,44);
dt = median(diff(tSim));
assert(max(abs(diff(tSim)-dt)) < 1.0e-10, ...
    'The independent reference requires uniform sampling.');
assert(abs(dt-0.01) < 1.0e-12, ...
    'The executable sample grid differs from the declared 0.01-s grid.');

yReference = independentReference(tSim,cfg,plant,yawController, ...
    rudder,controller,aileron);
errorSignal = ySim-yReference;
result.t = tSim;
result.ySim = ySim;
result.yReference = yReference;
result.maxError = max(abs(errorSignal),[],'all');
result.rmsError = sqrt(mean(errorSignal(:).^2));
result.configuration = cfg;
end

function cfg = captureConfiguration(caseName,controller,aileron)
cfg.name = caseName;
cfg.bankCommand_rad = 0.0;
cfg.aileronBias_rad = 0.0;
cfg.aileronPulse_rad = 0.0;
cfg.rudderBias_rad = 0.0;
cfg.rudderPulse_rad = 0.0;
cfg.aileronPulseStart_s = 5.0;
cfg.aileronPulseEnd_s = 6.0;
cfg.rudderPulseStart_s = 5.0;
cfg.rudderPulseEnd_s = 6.0;
cfg.pNoiseAmplitude_radps = 0.0;
cfg.pNoiseFrequency_radps = aileron.noise.rollRateFrequency_radps;
cfg.phiNoiseAmplitude_rad = 0.0;
cfg.phiNoiseFrequency_radps = aileron.noise.bankAngleFrequency_radps;
cfg.antiWindupEnable = 1.0;
cfg.x0 = zeros(5,1);
cfg.stopTime_s = controller.validation.stopTime_s;

switch caseName
    case 'command'
        cfg.bankCommand_rad = deg2rad(controller.validation.commandStep_deg);
    case 'initial'
        cfg.x0(4) = deg2rad(controller.validation.initialBankDisturbance_deg);
    case 'bias'
        cfg.aileronBias_rad = ...
            deg2rad(controller.validation.constantAileronBias_deg);
    case 'aileronPulse'
        cfg.aileronPulse_rad = deg2rad(1.0);
        cfg.stopTime_s = 30.0;
    case 'rudderPulse'
        cfg.rudderPulse_rad = deg2rad(1.0);
        cfg.stopTime_s = 30.0;
    case 'commandLimit'
        cfg.bankCommand_rad = deg2rad(30.0);
    case 'stressAw'
        cfg.x0(4) = deg2rad(aileron.stress.initialBank_deg);
        cfg.antiWindupEnable = 1.0;
        cfg.stopTime_s = aileron.stress.stopTime_s;
    case 'stressNoAw'
        cfg.x0(4) = deg2rad(aileron.stress.initialBank_deg);
        cfg.antiWindupEnable = 0.0;
        cfg.stopTime_s = aileron.stress.stopTime_s;
    case 'noise'
        multiplier = aileron.sensor.noiseStressMultiplier;
        cfg.pNoiseAmplitude_radps = deg2rad(sqrt(2)*multiplier* ...
            aileron.sensor.rollRateNoiseRms_degps);
        cfg.phiNoiseAmplitude_rad = deg2rad(sqrt(2)*multiplier* ...
            aileron.sensor.bankAngleNoiseRms_deg);
        cfg.stopTime_s = aileron.noise.stopTime_s;
    otherwise
        error('Unknown capture name: %s',caseName);
end
end

function y = independentReference(t,cfg,plant,yawController,rudder, ...
    controller,aileron)
% Continuous z = [beta p r phi psi rSensor xw deltaR pSensor phiSensor
%                 xi deltaA filteredCommand].
z = [cfg.x0;zeros(8,1)];
delay.r = cfg.x0(3);
delay.p = cfg.x0(2);
delay.phi = cfg.x0(4);
y = zeros(numel(t),44);
for k = 1:numel(t)
    d = protectedSignals(t(k),z,delay,cfg,yawController,rudder, ...
        controller,aileron);
    y(k,:) = outputVector(z,d).';
    if k < numel(t)
        h = t(k+1)-t(k);
        sampled.r = z(3);
        sampled.p = z(2);
        sampled.phi = z(4);
        k1 = protectedDerivative(t(k),z,delay,cfg,plant, ...
            yawController,rudder,controller,aileron);
        k2 = protectedDerivative(t(k)+0.5*h,z+0.5*h*k1,delay,cfg, ...
            plant,yawController,rudder,controller,aileron);
        k3 = protectedDerivative(t(k)+0.5*h,z+0.5*h*k2,delay,cfg, ...
            plant,yawController,rudder,controller,aileron);
        k4 = protectedDerivative(t(k)+h,z+h*k3,delay,cfg,plant, ...
            yawController,rudder,controller,aileron);
        z = z+(h/6)*(k1+2*k2+2*k3+k4);
        delay = sampled;
    end
end
end

function zDot = protectedDerivative(t,z,delay,cfg,plant, ...
    yawController,rudder,controller,aileron)
d = protectedSignals(t,z,delay,cfg,yawController,rudder, ...
    controller,aileron);
zDot = zeros(13,1);
zDot(1:5) = plant.A*z(1:5)+plant.B*[d.totalAileron;d.totalRudder];
zDot(6) = (d.rInput-z(6))/rudder.sensor.filterTimeConstant_s;
zDot(7) = (z(6)-z(7))/yawController.washoutTimeConstant_s;
zDot(8) = d.rudderRate;
zDot(9) = (d.pInput-z(9))/aileron.sensor.filterTimeConstant_s;
zDot(10) = (d.phiInput-z(10))/aileron.sensor.filterTimeConstant_s;
zDot(11) = d.bankError+d.antiWindup;
zDot(12) = d.aileronRate;
zDot(13) = (d.commandLimited-z(13))/ ...
    controller.commandFilterTimeConstant_s;
end

function d = protectedSignals(t,z,delay,cfg,yawController,rudder, ...
    controller,aileron)
d.commandRaw = cfg.bankCommand_rad;
d.commandLimited = clip(d.commandRaw, ...
    controller.commandAuthority.lowerLimit_rad, ...
    controller.commandAuthority.upperLimit_rad);
[d.aileronPilot,d.rudderPilot] = pilotInputs(t,cfg);
d.rNoise = 0.0;
d.pNoise = cfg.pNoiseAmplitude_radps*sin(cfg.pNoiseFrequency_radps*t);
d.phiNoise = cfg.phiNoiseAmplitude_rad*sin(cfg.phiNoiseFrequency_radps*t);
d.rDelayed = delay.r;
d.pDelayed = delay.p;
d.phiDelayed = delay.phi;
d.rInput = d.rDelayed+d.rNoise;
d.pInput = d.pDelayed+d.pNoise;
d.phiInput = d.phiDelayed+d.phiNoise;

d.rWashout = z(6)-z(7);
d.rudderRaw = -yawController.rudderGain_s*d.rWashout;
d.rudderPosition = clip(d.rudderRaw,rudder.authority.lowerLimit_rad, ...
    rudder.authority.upperLimit_rad);
d.rudderRateRaw = (d.rudderPosition-z(8))/ ...
    rudder.dynamics.timeConstant_s;
d.rudderRate = clip(d.rudderRateRaw, ...
    -deg2rad(rudder.dynamics.rateLimit_degps), ...
    deg2rad(rudder.dynamics.rateLimit_degps));
d.rudderTotalRaw = d.rudderPilot+z(8);
d.totalRudder = clip(d.rudderTotalRaw, ...
    rudder.physicalTravel.lowerLimit_rad, ...
    rudder.physicalTravel.upperLimit_rad);

d.bankError = z(13)-z(10);
d.proportional = controller.bankProportionalGain*d.bankError;
d.integral = controller.bankIntegralGain_per_s*z(11);
d.rollRateContribution = -controller.rollRateGain_s*z(9);
d.aileronUnsat = d.proportional+d.integral+d.rollRateContribution;
d.aileronPosition = clip(d.aileronUnsat, ...
    aileron.authority.lowerLimit_rad,aileron.authority.upperLimit_rad);
d.aileronRateRaw = (d.aileronPosition-z(12))/ ...
    aileron.dynamics.timeConstant_s;
d.aileronRate = clip(d.aileronRateRaw, ...
    -deg2rad(aileron.dynamics.rateLimit_degps), ...
    deg2rad(aileron.dynamics.rateLimit_degps));
d.aileronTrack = z(12)+ ...
    aileron.dynamics.timeConstant_s*d.aileronRate;
d.antiWindup = cfg.antiWindupEnable*(d.aileronTrack-d.aileronUnsat)/( ...
    controller.bankIntegralGain_per_s* ...
    aileron.antiWindup.trackingTimeConstant_s);
d.aileronTotalRaw = d.aileronPilot+z(12);
d.totalAileron = clip(d.aileronTotalRaw, ...
    aileron.physicalTravel.lowerLimit_rad, ...
    aileron.physicalTravel.upperLimit_rad);
end

function y = outputVector(z,d)
y = [z(1:5);d.commandRaw;d.commandLimited;z(13); ...
    d.aileronPilot;d.rudderPilot;d.rDelayed;d.rNoise;d.rInput;z(6); ...
    d.rWashout;d.rudderRaw;d.rudderPosition;z(8);d.rudderRateRaw; ...
    d.rudderRate;d.rudderTotalRaw;d.totalRudder;d.pDelayed;d.pNoise; ...
    d.pInput;z(9);d.phiDelayed;d.phiNoise;d.phiInput;z(10); ...
    d.bankError;d.proportional;z(11);d.integral; ...
    d.rollRateContribution;d.aileronUnsat;d.aileronPosition;z(12); ...
    d.aileronRateRaw;d.aileronRate;d.aileronTrack;d.antiWindup; ...
    d.aileronTotalRaw;d.totalAileron];
end

function [aileronInput,rudderInput] = pilotInputs(t,cfg)
t = snapToEdges(t,[cfg.aileronPulseStart_s,cfg.aileronPulseEnd_s, ...
    cfg.rudderPulseStart_s,cfg.rudderPulseEnd_s]);
aileronInput = cfg.aileronBias_rad;
rudderInput = cfg.rudderBias_rad;
if t >= cfg.aileronPulseStart_s && t < cfg.aileronPulseEnd_s
    aileronInput = aileronInput+cfg.aileronPulse_rad;
end
if t >= cfg.rudderPulseStart_s && t < cfg.rudderPulseEnd_s
    rudderInput = rudderInput+cfg.rudderPulse_rad;
end
end

function t = snapToEdges(t,edges)
for k = 1:numel(edges)
    if abs(t-edges(k)) <= 1.0e-12
        t = edges(k);
        return;
    end
end
end

