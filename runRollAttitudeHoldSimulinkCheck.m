%% C172S Roll-Attitude Hold V1 - protected Simulink equivalence check

clc;
clear;
close all;

try
    load_system('simulink');
catch ME
    error('runRollAttitudeHoldSimulinkCheck:SimulinkUnavailable', ...
        'Unable to load Simulink. MATLAB reported:\n%s',ME.message);
end

data = c172sLateralDirectionalData();
[~,plant] = c172sLateralDirectionalPlant(data);
yawController = c172sYawDamperData();
rudder = c172sRudderActuatorData();
controller = c172sRollAttitudeControllerData();
aileron = c172sAileronActuatorData();
assertDependencies(data,yawController,rudder,controller,aileron);

% Rebuild the generated diagram so a stale or hand-edited SLX cannot
% influence the implementation-equivalence result.
modelName = buildC172sRollAttitudeHoldSimulink(true);

%% Nine independent executable captures

commandCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'command');
initialCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'initial');
biasCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'bias');
aileronPulseCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'aileronPulse');
rudderPulseCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'rudderPulse');
commandLimitCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'commandLimit');
stressCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'stressAw');
stressNoAwCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'stressNoAw');
noiseCapture = runCapture(modelName,plant,yawController,rudder, ...
    controller,aileron,'noise');

captureNames = {'Command','Initial','Bias','Aileron pulse', ...
    'Rudder pulse','Command limit','Stress AW','Stress no-AW','Noise'};
captures = {commandCapture,initialCapture,biasCapture, ...
    aileronPulseCapture,rudderPulseCapture,commandLimitCapture, ...
    stressCapture,stressNoAwCapture,noiseCapture};

%% Independent hybrid-equivalence gates

tolerance = 1.0e-5;
for k = 1:numel(captures)
    assert(captures{k}.maxError < tolerance, ...
        '%s-capture error %.6g exceeds %.6g.', ...
        captureNames{k},captures{k}.maxError,tolerance);
end

assert(strcmp(get_param(modelName,'SolverType'),'Fixed-step'), ...
    'The generated model must use a fixed-step solver.');
assert(strcmp(get_param(modelName,'Solver'),'ode4'), ...
    'The generated model must use ode4.');
assert(abs(str2double(get_param(modelName,'FixedStep'))-0.01) < eps, ...
    'The generated model fixed step must be 0.01 s.');
assert(strcmp(get_param([modelName '/Bank Command Limit'],'UpperLimit'), ...
    'bankCommandUpper_rah1_rad'),'The bank-command authority changed.');
assert(strcmp(get_param([modelName '/Command Filter'],'A'), ...
    '-1/Tcmd_rah1'),'The bank-command filter changed.');

rollPath = [modelName '/Protected Roll Controller and Aileron'];
yawPath = [modelName '/Frozen Protected Yaw Damper V2'];
assert(strcmp(get_param([rollPath '/p Pure Delay'],'SampleTime'), ...
    'delaySampleTime_rah1'),'The p-channel pure delay changed.');
assert(strcmp(get_param([rollPath '/Phi Pure Delay'],'SampleTime'), ...
    'delaySampleTime_rah1'),'The phi-channel pure delay changed.');
assert(strcmp(get_param([yawPath '/r Pure Delay'],'SampleTime'), ...
    'delaySampleTime_rah1'),'The yaw-channel pure delay changed.');
assert(strcmp(get_param([rollPath '/p Sensor Filter'],'A'), ...
    '-1/TsRoll_rah1'),'The p sensor filter changed.');
assert(strcmp(get_param([rollPath '/Phi Sensor Filter'],'A'), ...
    '-1/TsRoll_rah1'),'The phi sensor filter changed.');
assert(strcmp(get_param([rollPath '/Bank Proportional Gain Kphi'],'Gain'), ...
    'Kphi_rah1'),'The bank proportional gain changed.');
assert(strcmp(get_param([rollPath '/Bank Integral Gain Ki'],'Gain'), ...
    'Ki_rah1'),'The bank integral gain changed.');
assert(strcmp(get_param([rollPath '/Roll-Rate Gain -Kp'],'Gain'), ...
    '-Kp_rah1'),'The roll-rate feedback sign or gain changed.');
assert(strcmp(get_param([rollPath '/Automatic Aileron Position Limit'], ...
    'UpperLimit'),'autoAileronUpper_rah1_rad'), ...
    'The automatic-aileron authority changed.');
assert(strcmp(get_param([rollPath '/Aileron Servo Rate Limit'], ...
    'UpperLimit'),'aileronRateUpper_rah1_radps'), ...
    'The aileron rate limit changed.');
assert(strcmp(get_param([rollPath '/Anti-Windup Scale'],'Gain'), ...
    '1/(Ki_rah1*Tt_rah1)'), ...
    'The anti-windup tracking law changed.');
assert(strcmp(get_param([yawPath '/Automatic Rudder Gain'],'Gain'), ...
    '-Kr_rah1'),'The frozen yaw-damper sign or gain changed.');
assert(strcmp(get_param([modelName '/Physical Aileron Hard Stop'], ...
    'UpperLimit'),'totalAileronUpper_rah1_rad'), ...
    'The physical aileron hard stop changed.');
assert(strcmp(get_param([modelName '/Physical Rudder Hard Stop'], ...
    'UpperLimit'),'totalRudderUpper_rah1_rad'), ...
    'The physical rudder hard stop changed.');

%% Exact signal identities, signs and summations

I = signalIndices();
for k = 1:numel(captures)
    y = captures{k}.ySim;
    cfg = captures{k}.configuration;

    assert(max(abs(y(:,I.commandLimited)-clip(y(:,I.commandRaw), ...
        controller.commandAuthority.lowerLimit_rad, ...
        controller.commandAuthority.upperLimit_rad))) < 1.0e-12, ...
        'Bank-command limiting is inconsistent.');
    assert(max(abs(y(:,I.rInput)-(y(:,I.rDelayed)+y(:,I.rNoise)))) < ...
        1.0e-12,'Yaw sensor summation is inconsistent.');
    assert(max(abs(y(:,I.pInput)-(y(:,I.pDelayed)+y(:,I.pNoise)))) < ...
        1.0e-12,'Roll-rate sensor summation is inconsistent.');
    assert(max(abs(y(:,I.phiInput)-(y(:,I.phiDelayed)+ ...
        y(:,I.phiNoise)))) < 1.0e-12, ...
        'Bank-angle sensor summation is inconsistent.');
    assert(max(abs(y(:,I.bankError)-(y(:,I.commandFiltered)- ...
        y(:,I.phiSensor)))) < 1.0e-12, ...
        'The bank-error sign or summation is inconsistent.');
    assert(max(abs(y(:,I.proportional)- ...
        controller.bankProportionalGain*y(:,I.bankError))) < 1.0e-12, ...
        'The proportional contribution is inconsistent.');
    assert(max(abs(y(:,I.integral)- ...
        controller.bankIntegralGain_per_s*y(:,I.xi))) < 1.0e-12, ...
        'The integral contribution is inconsistent.');
    assert(max(abs(y(:,I.rollRateContribution)+ ...
        controller.rollRateGain_s*y(:,I.pSensor))) < 1.0e-12, ...
        'The roll-rate damping contribution is inconsistent.');
    assert(max(abs(y(:,I.aileronUnsat)-(y(:,I.proportional)+ ...
        y(:,I.integral)+y(:,I.rollRateContribution)))) < 1.0e-12, ...
        'The unsaturated automatic-aileron sum is inconsistent.');
    assert(max(abs(y(:,I.aileronPosition)-clip(y(:,I.aileronUnsat), ...
        aileron.authority.lowerLimit_rad, ...
        aileron.authority.upperLimit_rad))) < 1.0e-12, ...
        'Automatic-aileron position limiting is inconsistent.');
    assert(max(abs(y(:,I.aileronRateRaw)-(y(:,I.aileronPosition)- ...
        y(:,I.aileronActual))/aileron.dynamics.timeConstant_s)) < 1.0e-10, ...
        'The raw aileron-servo rate is inconsistent.');
    assert(max(abs(y(:,I.aileronRate)-clip(y(:,I.aileronRateRaw), ...
        -deg2rad(aileron.dynamics.rateLimit_degps), ...
        deg2rad(aileron.dynamics.rateLimit_degps)))) < 1.0e-12, ...
        'Aileron-servo rate limiting is inconsistent.');
    assert(max(abs(y(:,I.aileronTrack)-(y(:,I.aileronActual)+ ...
        aileron.dynamics.timeConstant_s*y(:,I.aileronRate)))) < 1.0e-12, ...
        'The rate-aware aileron tracking value is inconsistent.');
    expectedAw = cfg.antiWindupEnable*(y(:,I.aileronTrack)- ...
        y(:,I.aileronUnsat))/(controller.bankIntegralGain_per_s* ...
        aileron.antiWindup.trackingTimeConstant_s);
    assert(max(abs(y(:,I.antiWindup)-expectedAw)) < 1.0e-10, ...
        'The anti-windup correction is inconsistent.');
    assert(max(abs(y(:,I.aileronTotalRaw)-(y(:,I.aileronPilot)+ ...
        y(:,I.aileronActual)))) < 1.0e-12, ...
        'Pilot plus automatic aileron summation is inconsistent.');
    assert(max(abs(y(:,I.aileronTotal)-clip(y(:,I.aileronTotalRaw), ...
        aileron.physicalTravel.lowerLimit_rad, ...
        aileron.physicalTravel.upperLimit_rad))) < 1.0e-12, ...
        'Physical aileron limiting is inconsistent.');

    assert(max(abs(y(:,I.rudderPosition)-clip(y(:,I.rudderRaw), ...
        rudder.authority.lowerLimit_rad,rudder.authority.upperLimit_rad))) < ...
        1.0e-12,'Automatic-rudder position limiting is inconsistent.');
    assert(max(abs(y(:,I.rudderRate)-clip(y(:,I.rudderRateRaw), ...
        -deg2rad(rudder.dynamics.rateLimit_degps), ...
        deg2rad(rudder.dynamics.rateLimit_degps)))) < 1.0e-12, ...
        'Rudder-servo rate limiting is inconsistent.');
    assert(max(abs(y(:,I.rudderTotalRaw)-(y(:,I.rudderPilot)+ ...
        y(:,I.rudderActual)))) < 1.0e-12, ...
        'Pilot plus automatic rudder summation is inconsistent.');
    assert(max(abs(y(:,I.rudderTotal)-clip(y(:,I.rudderTotalRaw), ...
        rudder.physicalTravel.lowerLimit_rad, ...
        rudder.physicalTravel.upperLimit_rad))) < 1.0e-12, ...
        'Physical rudder limiting is inconsistent.');
end

positiveError = find(commandCapture.ySim(:,I.bankError) > deg2rad(0.01), ...
    1,'first');
assert(~isempty(positiveError) && ...
    commandCapture.ySim(positiveError,I.proportional) > 0 && ...
    commandCapture.ySim(positiveError,I.aileronUnsat) > 0, ...
    'Positive bank error did not command positive right-wing-down aileron.');
positiveRollRate = find(commandCapture.ySim(:,I.pSensor) > ...
    deg2rad(0.01),1,'first');
assert(~isempty(positiveRollRate) && ...
    commandCapture.ySim(positiveRollRate,I.rollRateContribution) < 0, ...
    'Positive roll rate did not produce negative damping aileron.');
positiveYawRate = find(commandCapture.ySim(:,I.rSensor) > ...
    deg2rad(0.01),1,'first');
assert(~isempty(positiveYawRate) && ...
    commandCapture.ySim(positiveYawRate,I.rudderRaw) < 0, ...
    'Positive yaw rate did not produce negative damping rudder.');

%% Command, regulation and pilot-interaction gates

req = controller.requirements;
command_rad = deg2rad(controller.validation.commandStep_deg);
commandMetrics = positiveStepMetrics(commandCapture.t, ...
    commandCapture.ySim(:,I.phi),command_rad);
commandFinalError_deg = abs(rad2deg(command_rad- ...
    commandCapture.ySim(end,I.phi)));
commandPeakRollRate_degps = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.p))));
commandPeakAileron_deg = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.aileronActual))));
commandPeakRudder_deg = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.rudderActual))));
commandPeakBeta_deg = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.beta))));
commandPeakYawRate_degps = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.r))));
commandPeakAileronRate_degps = max(abs(rad2deg( ...
    commandCapture.ySim(:,I.aileronRate))));

assert(commandMetrics.riseTime_s >= req.minimumRiseTime_s && ...
    commandMetrics.riseTime_s <= req.maximumRiseTime_s, ...
    'The executable command rise time failed its gate.');
assert(commandMetrics.overshoot_pct <= req.maximumStepOvershoot_pct, ...
    'The executable command overshoot failed its gate.');
assert(commandMetrics.settlingTime_s <= req.maximumSettlingTime_s, ...
    'The executable command settling time failed its gate.');
assert(commandFinalError_deg <= req.maximumFinalBankError_deg, ...
    'The executable final bank error failed its gate.');
assert(commandPeakRollRate_degps <= req.maximumRollRate_degps, ...
    'The executable command exceeded the roll-rate gate.');
assert(commandPeakAileron_deg <= req.maximumAutomaticAileron_deg, ...
    'The executable command exceeded automatic-aileron effort.');
assert(commandPeakRudder_deg <= req.maximumAutomaticRudder_deg, ...
    'The executable command exceeded automatic-rudder effort.');
assert(commandPeakBeta_deg <= req.maximumSideslip_deg, ...
    'The executable command exceeded the sideslip gate.');
assert(commandPeakYawRate_degps <= req.maximumYawRate_degps, ...
    'The executable command exceeded the yaw-rate gate.');
assert(commandPeakAileronRate_degps <= ...
    aileron.requirements.maximumOperationalActuatorRate_degps, ...
    'The executable command exceeded the operational aileron-rate gate.');
assert(~aileronPositionLimitActive(commandCapture.ySim,I) && ...
    ~aileronRateLimitActive(commandCapture.ySim,I), ...
    'Aileron protection unexpectedly activated for the 10-deg command.');

initialFinalBank_deg = abs(rad2deg(initialCapture.ySim(end,I.phi)));
initialPeakAutomaticAileron_deg = max(abs(rad2deg( ...
    initialCapture.ySim(:,I.aileronActual))));
initialPeakAileronRate_degps = max(abs(rad2deg( ...
    initialCapture.ySim(:,I.aileronRate))));
biasFinalBank_deg = abs(rad2deg(biasCapture.ySim(end,I.phi)));
biasFinalAutomaticAileron_deg = rad2deg( ...
    biasCapture.ySim(end,I.aileronActual));
assert(initialFinalBank_deg <= req.maximumRegulationResidual_deg, ...
    'Initial-bank regulation failed.');
assert(initialPeakAutomaticAileron_deg <= ...
    aileron.authority.rightWingDown_deg+1.0e-9 && ...
    initialPeakAileronRate_degps <= ...
    aileron.dynamics.rateLimit_degps+1.0e-9, ...
    'Initial-bank recovery exceeded protected aileron capability.');
assert(biasFinalBank_deg <= req.maximumRegulationResidual_deg, ...
    'Constant pilot-aileron-bias regulation failed.');
assert(abs(biasFinalAutomaticAileron_deg+ ...
    controller.validation.constantAileronBias_deg) <= 0.01, ...
    'The integrator did not cancel the constant pilot-aileron bias.');

aileronPulsePeakBank_deg = max(abs(rad2deg( ...
    aileronPulseCapture.ySim(:,I.phi))));
rudderPulsePeakBank_deg = max(abs(rad2deg( ...
    rudderPulseCapture.ySim(:,I.phi))));
aileronPulseFinalBank_deg = abs(rad2deg( ...
    aileronPulseCapture.ySim(end,I.phi)));
rudderPulseFinalBank_deg = abs(rad2deg( ...
    rudderPulseCapture.ySim(end,I.phi)));
assert(aileronPulseFinalBank_deg <= req.maximumRegulationResidual_deg && ...
    rudderPulseFinalBank_deg <= req.maximumRegulationResidual_deg, ...
    'A pilot-pulse capture did not return to the commanded bank.');
operationalCaptures = {commandCapture,initialCapture,biasCapture, ...
    aileronPulseCapture,rudderPulseCapture};
for k = 1:numel(operationalCaptures)
    assert(~aileronPositionLimitActive(operationalCaptures{k}.ySim,I) && ...
        ~aileronRateLimitActive(operationalCaptures{k}.ySim,I) && ...
        ~aileronPhysicalLimitActive(operationalCaptures{k}.ySim,I), ...
        'Aileron protection unexpectedly activated operationally.');
    assert(~rudderPositionLimitActive(operationalCaptures{k}.ySim,I) && ...
        ~rudderRateLimitActive(operationalCaptures{k}.ySim,I) && ...
        ~rudderPhysicalLimitActive(operationalCaptures{k}.ySim,I), ...
        'Rudder protection unexpectedly activated operationally.');
end

%% Command-limit, actuator-stress, anti-windup and noise gates

commandLimitActive = any(abs(commandLimitCapture.ySim(:,I.commandRaw)- ...
    commandLimitCapture.ySim(:,I.commandLimited)) > 1.0e-10);
commandLimitMaximum_deg = max(abs(rad2deg( ...
    commandLimitCapture.ySim(:,I.commandLimited))));
commandLimitFinalBank_deg = rad2deg( ...
    commandLimitCapture.ySim(end,I.phi));
assert(commandLimitActive, ...
    'The 30-deg bank command did not activate command limiting.');
assert(abs(commandLimitMaximum_deg- ...
    controller.commandAuthority.rightWingDown_deg) < 1.0e-9, ...
    'The executable bank-command authority is incorrect.');
assert(abs(commandLimitFinalBank_deg- ...
    controller.commandAuthority.rightWingDown_deg) <= ...
    req.maximumFinalBankError_deg, ...
    'The command-limited capture did not settle at 20 deg.');

stressMetrics = protectedStressMetrics(stressCapture,I,aileron);
stressNoAwMetrics = protectedStressMetrics(stressNoAwCapture,I,aileron);
antiWindupIntegratorRatio = stressMetrics.peakIntegratorMagnitude/ ...
    stressNoAwMetrics.peakIntegratorMagnitude;
assert(stressMetrics.positionLimitActive && stressMetrics.rateLimitActive, ...
    'The 30-deg initial-bank stress did not activate both aileron limits.');
assert(~stressMetrics.physicalLimitActive, ...
    'The logic stress unexpectedly reached the physical aileron stop.');
assert(stressMetrics.peakAutomaticAileron_deg <= ...
    aileron.authority.rightWingDown_deg+1.0e-9, ...
    'The stress case exceeded automatic-aileron authority.');
assert(stressMetrics.peakAileronRate_degps <= ...
    aileron.dynamics.rateLimit_degps+1.0e-9, ...
    'The stress case exceeded the aileron-rate limit.');
assert(stressMetrics.recoveryTime_s <= ...
    aileron.stress.maximumRecoveryTime_s, ...
    'The stress case recovered too slowly.');
assert(abs(stressMetrics.finalBank_deg) <= ...
    aileron.stress.maximumFinalBank_deg, ...
    'The stress-case final bank residual is excessive.');
assert(abs(stressMetrics.finalAutomaticAileron_deg) <= ...
    aileron.requirements.maximumReleasedAileron_deg, ...
    'The automatic aileron did not release after the stress.');
assert(antiWindupIntegratorRatio <= ...
    aileron.stress.maximumAntiWindupIntegratorRatio, ...
    'Simulink anti-windup did not sufficiently reduce integrator growth.');

noiseRows = noiseCapture.t >= aileron.noise.discardTime_s;
noiseAileron_deg = rad2deg(noiseCapture.ySim(noiseRows,I.aileronActual));
noiseAileronRms_deg = sqrt(mean(noiseAileron_deg.^2));
noiseAileronPeak_deg = max(abs(noiseAileron_deg));
pNoiseRms_degps = sqrt(mean(rad2deg( ...
    noiseCapture.ySim(noiseRows,I.pNoise)).^2));
phiNoiseRms_deg = sqrt(mean(rad2deg( ...
    noiseCapture.ySim(noiseRows,I.phiNoise)).^2));
assert(noiseAileronRms_deg <= ...
    aileron.requirements.maximumNoiseActuatorRms_deg, ...
    'Roll-sensor noise exceeded the automatic-aileron RMS gate.');
assert(noiseAileronPeak_deg <= ...
    aileron.requirements.maximumNoiseActuatorPeak_deg, ...
    'Roll-sensor noise exceeded the automatic-aileron peak gate.');
assert(~aileronPositionLimitActive(noiseCapture.ySim,I) && ...
    ~aileronRateLimitActive(noiseCapture.ySim,I), ...
    'Sensor noise unexpectedly activated aileron protection.');

assert(aileron.sensor.nominalDelay_s <= ...
    aileron.sensor.maximumAcceptedDelay_s, ...
    'The executable roll delay exceeds the accepted 40-ms envelope.');
assert(rudder.sensor.nominalDelay_s <= ...
    rudder.sensor.maximumAcceptedDelay_s, ...
    'The executable yaw delay exceeds the accepted 60-ms envelope.');

