function writeManifest(path,versionTag,fileNames,releaseFolder)
fid = fopen(path,'w');
assert(fid >= 0, ...
    'prepareC172sNonlinearAutopilotRelease:ManifestWriteFailed', ...
    'Unable to write release manifest: %s',path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

generated = datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z''');
fprintf(fid,'C172S NONLINEAR AUTOPILOT - RELEASE MANIFEST\n');
fprintf(fid,'Version: %s\n',versionTag);
fprintf(fid,'Generated UTC: %s\n',char(generated));
fprintf(fid,'MATLAB: %s\n',version);
fprintf(fid,'Nonlinear-autopilot regression: 3/3 PASS\n');
fprintf(fid,'Frozen flight-controls evidence: 18/18 PASS (external)\n');
fprintf(fid,'Frozen nonlinear-plant evidence: 7/7 PASS (external)\n');
fprintf(fid,'Combined project evidence: 28/28 PASS\n');
fprintf(fid,['Scope: frozen flight-controls v1.0.0 operating one coupled ', ...
    'nonlinear 13-state research plant v0.1.0 through the frozen Mode ', ...
    'Manager, protected controller stack and executable Simulink model.\n']);
fprintf(fid,['Qualification: 80-130 KTAS, alpha -4 to +10 deg, beta ', ...
    '+/-8 deg, flaps up, near-trim attached flow, provisional mass ', ...
    'properties, ideal sensors and one-point throttle; no stall/spin, ', ...
    'autothrottle or aircraft-truth claim; not aircraft approval.\n\n']);
fprintf(fid,'Packaged files:\n');

allNames = sort([fileNames; {'RELEASE_MANIFEST.txt'}]);
for k = 1:numel(allNames)
    info = dir(fullfile(releaseFolder,allNames{k}));
    if isempty(info)
        bytes = 0;
    else
        bytes = info(1).bytes;
    end
    fprintf(fid,'%10d  %s\n',bytes,allNames{k});
end
end
