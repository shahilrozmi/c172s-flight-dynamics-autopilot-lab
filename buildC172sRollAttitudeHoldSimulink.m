function modelName = buildC172sRollAttitudeHoldSimulink(forceRebuild)
%BUILDC172SROLLATTITUDEHOLDSIMULINK Build protected roll-attitude hold V1.
%
%   MODELNAME = BUILDC172SROLLATTITUDEHOLDSIMULINK() creates or opens
%   C172S_RollAttitudeHold_V1.slx in the current folder.
%
%   MODELNAME = BUILDC172SROLLATTITUDEHOLDSIMULINK(true) overwrites only
%   the generated SLX file. Frozen Plant V0.1, Yaw Damper V2 and MATLAB
%   roll-controller/source-audit artifacts are not altered.

arguments
    forceRebuild (1,1) logical = false
end

modelName = 'C172S_RollAttitudeHold_V1';
modelFile = fullfile(pwd,[modelName '.slx']);

%% Initialize frozen dependencies and selected assumptions

rah1Data = c172sLateralDirectionalData();
[~,rah1Plant] = c172sLateralDirectionalPlant(rah1Data);
rah1YawController = c172sYawDamperData();
rah1RudderActuator = c172sRudderActuatorData();
rah1Controller = c172sRollAttitudeControllerData();
rah1AileronActuator = c172sAileronActuatorData();
assertDependencies(rah1Data,rah1YawController,rah1RudderActuator, ...
    rah1Controller,rah1AileronActuator);
assignModelVariables(rah1Data,rah1Plant,rah1YawController, ...
    rah1RudderActuator,rah1Controller,rah1AileronActuator);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    load_system(modelFile);
    open_system(modelName);
    fprintf('Opened existing model: %s\n',modelFile);
    return;
end
if isfile(modelFile) && forceRebuild
    delete(modelFile);
end

%% Create and configure executable model

new_system(modelName);
open_system(modelName);
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','ode4', ...
    'FixedStep','0.01', ...
    'StartTime','0', ...
    'StopTime','40', ...
    'SaveTime','on', ...
    'TimeSaveName','tout', ...
    'SaveOutput','on', ...
    'OutputSaveName','yout', ...
    'SaveFormat','Array');

% Immutable definitions are rebuilt before each run. SimulationInput/base-
% workspace overrides of commands, initial conditions, noise and the
% anti-windup switch are deliberately preserved.
