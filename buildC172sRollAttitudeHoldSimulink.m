    'A','-1/TsRoll_rah1','B','1/TsRoll_rah1','C','1','D','0', ...
    'X0','pSensor0_rah1_radps','Position',[310 195 420 245]);
add_block('simulink/Math Operations/Gain',[path '/Roll-Rate Gain -Kp'], ...
    'Gain','-Kp_rah1','Position',[470 200 575 240]);

