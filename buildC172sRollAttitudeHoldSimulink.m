function assertDependencies(data,yawController,rudder,controller,aileron)
assert(strcmp(data.model.version,controller.requiredPlantVersion), ...
    'Roll-Attitude Hold V1 plant dependency mismatch.');
assert(strcmp(yawController.artifactRevision, ...
    controller.requiredYawDamperRevision), ...
    'Roll-Attitude Hold V1 yaw-controller dependency mismatch.');
assert(strcmp(rudder.artifactRevision, ...
    controller.requiredRudderAuditRevision), ...
    'Roll-Attitude Hold V1 rudder-audit dependency mismatch.');
assert(strcmp(aileron.artifactRevision, ...
    controller.requiredAileronAuditRevision), ...
    'Roll-Attitude Hold V1 aileron-audit dependency mismatch.');
assert(abs(aileron.sensor.nominalDelay_s-0.010) < 1.0e-12, ...
    'The executable baseline requires the audited 10-ms roll delay.');
assert(abs(rudder.sensor.nominalDelay_s-0.010) < 1.0e-12, ...
    'The executable baseline requires the audited 10-ms yaw delay.');
end

