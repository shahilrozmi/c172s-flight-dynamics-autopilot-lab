end

function check = makeCheck(domain,name,artifact,checker)
check = struct('Domain',domain,'Name',name, ...
    'Artifact',artifact,'Checker',checker);
end

function writeRegressionReport(reportFile,results,passCount,failCount)
fid = fopen(reportFile,'w');
if fid < 0
    error('runAllFlightControlChecks:ReportWriteFailed', ...
        'Unable to write regression report: %s',reportFile);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid,'C172S FLIGHT CONTROLS - MASTER REGRESSION REPORT\n');
fprintf(fid,'Generated: %s\n',datestr(now,31)); %#ok<DATST>
fprintf(fid,'MATLAB: %s\n',version);
fprintf(fid,['Scope: longitudinal release plus lateral stack through ', ...
    'executable Integrated Autopilot V1\n']);
fprintf(fid,'Passed: %d/%d\n',passCount,numel(results));
fprintf(fid,'Failed: %d/%d\n\n',failCount,numel(results));

domains = unique({results.Domain},'stable');
for iDomain = 1:numel(domains)
    selected = strcmp({results.Domain},domains{iDomain});
    fprintf(fid,'%s: %d/%d passed\n',domains{iDomain}, ...
        sum(strcmp({results(selected).Status},'PASS')),sum(selected));
end
fprintf(fid,['\nQualification: lateral dynamics use provisional Plant V0.1; ', ...
    'supervisory thresholds, timers and other declared values remain ', ...
    'project assumptions. This report is not aircraft approval.\n\n']);

for k = 1:numel(results)
    fprintf(fid,'============================================================\n');
    fprintf(fid,'%d. [%s] %s\n',k,results(k).Domain,results(k).Name);
    fprintf(fid,'Artifact: %s\n',results(k).Artifact);
    fprintf(fid,'Checker: %s.m\n',results(k).Checker);
    fprintf(fid,'Path: %s\n',results(k).Path);
    fprintf(fid,'Status: %s\n',results(k).Status);
    fprintf(fid,'Duration: %.3f s\n',results(k).Duration_s);
    if ~isempty(results(k).Identifier)
        fprintf(fid,'Identifier: %s\n',results(k).Identifier);
    end
    if ~isempty(results(k).Message)
        fprintf(fid,'Message: %s\n',results(k).Message);
    end
    fprintf(fid,'\nCaptured output:\n%s\n\n',results(k).Output);
end
end

function text = oneLine(text)
text = regexprep(text,'\s+',' ');
text = strtrim(text);
end
