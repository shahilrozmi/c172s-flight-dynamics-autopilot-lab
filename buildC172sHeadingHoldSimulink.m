function modelName = buildC172sHeadingHoldSimulink(forceRebuild)
%BUILDC172SHEADINGHOLDSIMULINK Build protected Heading Hold V1.
%
%   MODELNAME = BUILDC172SHEADINGHOLDSIMULINK() creates or opens
%   C172S_HeadingHold_V1.slx in the current folder.
%
%   MODELNAME = BUILDC172SHEADINGHOLDSIMULINK(true) overwrites only
%   the generated SLX file. Frozen Plant V0.1, Yaw Damper V2,
%   Roll-Attitude Hold V1 and every source-audit artifact are unaltered.

arguments
    forceRebuild (1,1) logical = false
end

modelName = 'C172S_HeadingHold_V1';
modelFile = fullfile(pwd,[modelName '.slx']);

%% Initialize frozen dependencies and selected assumptions

hh1Data = c172sLateralDirectionalData();
[~,hh1Plant] = c172sLateralDirectionalPlant(hh1Data);
hh1YawController = c172sYawDamperData();
hh1RudderActuator = c172sRudderActuatorData();
hh1RollController = c172sRollAttitudeControllerData();
hh1AileronActuator = c172sAileronActuatorData();
hh1HeadingSensor = c172sHeadingSensorData();
hh1HeadingController = c172sHeadingHoldControllerData();
assertDependencies(hh1Data,hh1YawController,hh1RudderActuator, ...
    hh1RollController,hh1AileronActuator,hh1HeadingSensor, ...
    hh1HeadingController);
assignModelVariables(hh1Data,hh1Plant,hh1YawController, ...
    hh1RudderActuator,hh1RollController,hh1AileronActuator, ...
    hh1HeadingSensor,hh1HeadingController);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    load_system(modelFile);
    open_system(modelName);
    fprintf('Opened existing model: %s\n',modelFile);
    return;
end
if isfile(modelFile) && forceRebuild
    delete(modelFile);
end

%% Create and configure executable model

new_system(modelName);
open_system(modelName);
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','ode4', ...
    'FixedStep','0.01', ...
    'StartTime','0', ...
    'StopTime','100', ...
    'SaveTime','on', ...
    'TimeSaveName','tout', ...
    'SaveOutput','on', ...
    'OutputSaveName','yout', ...
    'SaveFormat','Array');

% Immutable definitions are rebuilt before each run. SimulationInput/base-
% workspace overrides of commands, initial conditions, noise and the
% anti-windup switch are deliberately preserved.
initCode = [ ...
    'hh1Data = c172sLateralDirectionalData();' newline ...
    '[~,hh1Plant] = c172sLateralDirectionalPlant(hh1Data);' newline ...
    'hh1YawController = c172sYawDamperData();' newline ...
    'hh1RudderActuator = c172sRudderActuatorData();' newline ...
    'hh1RollController = c172sRollAttitudeControllerData();' newline ...
    'hh1AileronActuator = c172sAileronActuatorData();' newline ...
    'hh1HeadingSensor = c172sHeadingSensorData();' newline ...
    'hh1HeadingController = c172sHeadingHoldControllerData();' newline ...
    'if ~strcmp(hh1Data.model.version,hh1HeadingController.requiredPlantVersion), error(''HH V1 plant dependency mismatch.''); end' newline ...
    'if ~strcmp(hh1YawController.artifactRevision,hh1HeadingController.requiredYawDamperRevision), error(''HH V1 yaw-controller dependency mismatch.''); end' newline ...
    'if ~strcmp(hh1RudderActuator.artifactRevision,hh1HeadingController.requiredRudderAuditRevision), error(''HH V1 rudder-audit dependency mismatch.''); end' newline ...
    'if ~strcmp(hh1AileronActuator.artifactRevision,hh1HeadingController.requiredAileronAuditRevision), error(''HH V1 aileron-audit dependency mismatch.''); end' newline ...
    'if ~strcmp(hh1RollController.artifactRevision,hh1HeadingController.requiredRollControllerRevision), error(''HH V1 roll-controller dependency mismatch.''); end' newline ...
    'if ~strcmp(hh1HeadingSensor.artifactRevision,hh1HeadingController.requiredHeadingSensorRevision), error(''HH V1 heading-sensor dependency mismatch.''); end' newline ...
    'A_hh1 = hh1Plant.A; B_hh1 = hh1Plant.B;' newline ...
    'C_hh1 = hh1Plant.C; D_hh1 = hh1Plant.D;' newline ...
    'Kphi_hh1 = hh1RollController.bankProportionalGain;' newline ...
    'Ki_hh1 = hh1RollController.bankIntegralGain_per_s;' newline ...
    'Kp_hh1 = hh1RollController.rollRateGain_s;' newline ...
    'Tcmd_hh1 = hh1RollController.commandFilterTimeConstant_s;' newline ...
    'Kr_hh1 = hh1YawController.rudderGain_s;' newline ...
    'Tw_hh1 = hh1YawController.washoutTimeConstant_s;' newline ...
    'TsRudder_hh1 = hh1RudderActuator.sensor.filterTimeConstant_s;' newline ...
    'tauRudder_hh1 = hh1RudderActuator.dynamics.timeConstant_s;' newline ...
    'TsRoll_hh1 = hh1AileronActuator.sensor.filterTimeConstant_s;' newline ...
    'tauAileron_hh1 = hh1AileronActuator.dynamics.timeConstant_s;' newline ...
    'Tt_hh1 = hh1AileronActuator.antiWindup.trackingTimeConstant_s;' newline ...
    'delaySampleTime_hh1 = hh1AileronActuator.sensor.nominalDelay_s;' newline ...
    'Kpsi_hh1 = hh1HeadingController.headingErrorGain;' newline ...
    'TsHeading_hh1 = hh1HeadingSensor.filterTimeConstant_s;' newline ...
    'headingDelaySampleTime_hh1 = hh1HeadingSensor.nominalDelay_s/5;' newline ...
    'bankCommandLower_hh1_rad = -deg2rad(hh1HeadingController.bankCommandAuthority_deg);' newline ...
    'bankCommandUpper_hh1_rad = deg2rad(hh1HeadingController.bankCommandAuthority_deg);' newline ...
    'autoAileronLower_hh1_rad = hh1AileronActuator.authority.lowerLimit_rad;' newline ...
    'autoAileronUpper_hh1_rad = hh1AileronActuator.authority.upperLimit_rad;' newline ...
    'aileronRateLower_hh1_radps = -deg2rad(hh1AileronActuator.dynamics.rateLimit_degps);' newline ...
    'aileronRateUpper_hh1_radps = deg2rad(hh1AileronActuator.dynamics.rateLimit_degps);' newline ...
    'totalAileronLower_hh1_rad = hh1AileronActuator.physicalTravel.lowerLimit_rad;' newline ...
    'totalAileronUpper_hh1_rad = hh1AileronActuator.physicalTravel.upperLimit_rad;' newline ...
    'autoRudderLower_hh1_rad = hh1RudderActuator.authority.lowerLimit_rad;' newline ...
    'autoRudderUpper_hh1_rad = hh1RudderActuator.authority.upperLimit_rad;' newline ...
    'rudderRateLower_hh1_radps = -deg2rad(hh1RudderActuator.dynamics.rateLimit_degps);' newline ...
    'rudderRateUpper_hh1_radps = deg2rad(hh1RudderActuator.dynamics.rateLimit_degps);' newline ...
    'totalRudderLower_hh1_rad = hh1RudderActuator.physicalTravel.lowerLimit_rad;' newline ...
    'totalRudderUpper_hh1_rad = hh1RudderActuator.physicalTravel.upperLimit_rad;' newline ...
    'if ~exist(''headingCommand_hh1_rad'',''var''), headingCommand_hh1_rad = deg2rad(30); end' newline ...
    'if ~exist(''headingBias_hh1_rad'',''var''), headingBias_hh1_rad = 0; end' newline ...
    'if ~exist(''headingNoiseAmplitude_hh1_rad'',''var''), headingNoiseAmplitude_hh1_rad = 0; end' newline ...
    'if ~exist(''headingNoiseFrequency_hh1_radps'',''var''), headingNoiseFrequency_hh1_radps = 0.8; end' newline ...
    'if ~exist(''pilotAileronBias_hh1_rad'',''var''), pilotAileronBias_hh1_rad = 0; end' newline ...
    'if ~exist(''pilotAileronPulse_hh1_rad'',''var''), pilotAileronPulse_hh1_rad = 0; end' newline ...
    'if ~exist(''pilotRudderBias_hh1_rad'',''var''), pilotRudderBias_hh1_rad = 0; end' newline ...
    'if ~exist(''pilotRudderPulse_hh1_rad'',''var''), pilotRudderPulse_hh1_rad = 0; end' newline ...
    'if ~exist(''aileronPulseStart_hh1_s'',''var''), aileronPulseStart_hh1_s = 5; end' newline ...
    'if ~exist(''aileronPulseEnd_hh1_s'',''var''), aileronPulseEnd_hh1_s = 6; end' newline ...
    'if ~exist(''rudderPulseStart_hh1_s'',''var''), rudderPulseStart_hh1_s = 5; end' newline ...
    'if ~exist(''rudderPulseEnd_hh1_s'',''var''), rudderPulseEnd_hh1_s = 6; end' newline ...
    'if ~exist(''pNoiseAmplitude_hh1_radps'',''var''), pNoiseAmplitude_hh1_radps = 0; end' newline ...
    'if ~exist(''pNoiseFrequency_hh1_radps'',''var''), pNoiseFrequency_hh1_radps = 50; end' newline ...
    'if ~exist(''phiNoiseAmplitude_hh1_rad'',''var''), phiNoiseAmplitude_hh1_rad = 0; end' newline ...
    'if ~exist(''phiNoiseFrequency_hh1_radps'',''var''), phiNoiseFrequency_hh1_radps = 5; end' newline ...
    'if ~exist(''yawNoiseAmplitude_hh1_radps'',''var''), yawNoiseAmplitude_hh1_radps = 0; end' newline ...
    'if ~exist(''yawNoiseFrequency_hh1_radps'',''var''), yawNoiseFrequency_hh1_radps = 50; end' newline ...
    'if ~exist(''antiWindupEnable_hh1'',''var''), antiWindupEnable_hh1 = 1; end' newline ...
    'if ~exist(''x0_hh1'',''var''), x0_hh1 = zeros(5,1); end' newline ...
    'if ~exist(''rDelay0_hh1_radps'',''var''), rDelay0_hh1_radps = x0_hh1(3); end' newline ...
    'if ~exist(''pDelay0_hh1_radps'',''var''), pDelay0_hh1_radps = x0_hh1(2); end' newline ...
    'if ~exist(''phiDelay0_hh1_rad'',''var''), phiDelay0_hh1_rad = x0_hh1(4); end' newline ...
    'if ~exist(''rSensor0_hh1_radps'',''var''), rSensor0_hh1_radps = 0; end' newline ...
    'if ~exist(''xw0_hh1_radps'',''var''), xw0_hh1_radps = 0; end' newline ...
    'if ~exist(''deltaRAuto0_hh1_rad'',''var''), deltaRAuto0_hh1_rad = 0; end' newline ...
    'if ~exist(''pSensor0_hh1_radps'',''var''), pSensor0_hh1_radps = 0; end' newline ...
    'if ~exist(''phiSensor0_hh1_rad'',''var''), phiSensor0_hh1_rad = 0; end' newline ...
    'if ~exist(''psiDelay0_hh1_rad'',''var''), psiDelay0_hh1_rad = x0_hh1(5); end' newline ...
    'if ~exist(''psiSensor0_hh1_rad'',''var''), psiSensor0_hh1_rad = x0_hh1(5)+headingBias_hh1_rad; end' newline ...
    'if ~exist(''xi0_hh1_rad_s'',''var''), xi0_hh1_rad_s = 0; end' newline ...
    'if ~exist(''deltaAAuto0_hh1_rad'',''var''), deltaAAuto0_hh1_rad = 0; end' newline ...
    'if ~exist(''filteredCommand0_hh1_rad'',''var''), filteredCommand0_hh1_rad = 0; end'];
set_param(modelName,'InitFcn',initCode);

%% Heading command and pilot inputs

add_block('simulink/Sources/Step',[modelName '/Heading Command'], ...
    'Time','0','Before','0','After','headingCommand_hh1_rad', ...
    'SampleTime','0','Position',[35 115 115 145]);
add_block('simulink/Continuous/State-Space',[modelName '/Command Filter'], ...
    'A','-1/Tcmd_hh1','B','1/Tcmd_hh1','C','1','D','0', ...
    'X0','filteredCommand0_hh1_rad', ...
    'Position',[470 105 585 155]);

add_block('simulink/Sources/Constant',[modelName '/Aileron Bias'], ...
    'Value','pilotAileronBias_hh1_rad','Position',[35 260 105 290]);
