    [modelName '/Physical Aileron Hard Stop'], ...
    'LowerLimit','totalAileronLower_hh1_rad', ...
    'UpperLimit','totalAileronUpper_hh1_rad', ...
    'Position',[1095 275 1235 345]);
add_block('simulink/Math Operations/Sum',[modelName '/Raw Total Rudder'], ...
    'Inputs','++','Position',[1020 555 1050 605]);
add_block('simulink/Discontinuities/Saturation', ...
    [modelName '/Physical Rudder Hard Stop'], ...
    'LowerLimit','totalRudderLower_hh1_rad', ...
    'UpperLimit','totalRudderUpper_hh1_rad', ...
    'Position',[1095 545 1235 615]);
add_block('simulink/Signal Routing/Mux',[modelName '/Control Mux'], ...
    'Inputs','2','Position',[1280 365 1285 515]);
add_block('simulink/Continuous/State-Space', ...
    [modelName '/C172S Lateral-Directional Plant'], ...
    'A','A_hh1','B','B_hh1','C','C_hh1','D','D_hh1', ...
    'X0','x0_hh1','Position',[1340 400 1545 480]);
add_block('simulink/Signal Routing/Demux',[modelName '/State Demux'], ...
    'Outputs','5','Position',[1595 330 1600 550]);

headingPath = [modelName '/Heading Sensor and Outer Loop'];
add_block('simulink/Ports & Subsystems/Subsystem',headingPath, ...
    'Position',[150 70 425 190]);
buildHeadingSubsystem(headingPath);

rollPath = [modelName '/Frozen Protected Roll-Attitude Hold V1'];
add_block('simulink/Ports & Subsystems/Subsystem',rollPath, ...
    'Position',[630 135 945 380]);
buildRollSubsystem(rollPath);

yawPath = [modelName '/Frozen Protected Yaw Damper V2'];
add_block('simulink/Ports & Subsystems/Subsystem',yawPath, ...
    'Position',[630 500 945 650]);
buildYawSubsystem(yawPath);

