    'Time','aileronPulseStart_hh1_s','Before','0', ...
    'After','pilotAileronPulse_hh1_rad','SampleTime','0', ...
    'Position',[35 305 105 335]);
add_block('simulink/Sources/Step',[modelName '/Aileron Pulse End'], ...
    'Time','aileronPulseEnd_hh1_s','Before','0', ...
    'After','-pilotAileronPulse_hh1_rad','SampleTime','0', ...
    'Position',[35 350 105 380]);
add_block('simulink/Math Operations/Sum',[modelName '/Pilot Aileron'], ...
    'Inputs','+++','Position',[155 285 185 355]);

add_block('simulink/Sources/Constant',[modelName '/Rudder Bias'], ...
    'Value','pilotRudderBias_hh1_rad','Position',[35 535 105 565]);
add_block('simulink/Sources/Step',[modelName '/Rudder Pulse Start'], ...
    'Time','rudderPulseStart_hh1_s','Before','0', ...
    'After','pilotRudderPulse_hh1_rad','SampleTime','0', ...
    'Position',[35 580 105 610]);
add_block('simulink/Sources/Step',[modelName '/Rudder Pulse End'], ...
    'Time','rudderPulseEnd_hh1_s','Before','0', ...
    'After','-pilotRudderPulse_hh1_rad','SampleTime','0', ...
    'Position',[35 625 105 655]);
add_block('simulink/Math Operations/Sum',[modelName '/Pilot Rudder'], ...
    'Inputs','+++','Position',[155 560 185 630]);

%% Plant and protected controller subsystems

add_block('simulink/Math Operations/Sum',[modelName '/Raw Total Aileron'], ...
    'Inputs','++','Position',[1020 285 1050 335]);
